"""Domain models for the Everest Textile OS Intelligence & Recovery Engine."""

from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class RecoveryPlanStatus(str, Enum):
    DETECTED = "detected"
    ANALYZED = "analyzed"
    PROPOSED = "proposed"
    AWAITING_APPROVAL = "awaiting_approval"
    APPROVED = "approved"
    EXECUTING = "executing"
    EXECUTED = "executed"
    VERIFIED = "verified"
    REJECTED = "rejected"
    FAILED = "failed"
    CANCELLED = "cancelled"
    VERIFICATION_FAILED = "verification_failed"


class AnomalyFinding(BaseModel):
    """Specific abnormal condition detected in operational telemetry."""
    anomaly_id: str
    anomaly_type: str
    affected_entity_type: str  # machine, order, material, quality
    affected_entity_id: str
    observed_value: float
    expected_value: float
    threshold: float
    severity: str  # info, warning, critical
    time_window: str
    supporting_event_ids: List[str] = Field(default_factory=list)
    explanation: str
    timestamp: datetime


class BottleneckFinding(BaseModel):
    """Process stage identified as constraining factory throughput."""
    stage_name: str
    process_type: str
    rank: int = 1
    candidate_machine_ids: List[str] = Field(default_factory=list)
    queue_units: float = 0.0
    capacity_utilization_percent: float = 0.0
    actual_output_rate: float = 0.0
    starvation_risk: bool = False
    blockage_risk: bool = False
    evidence_summary: str
    severity: str = "medium"


class MaterialRiskAssessment(BaseModel):
    """Inventory availability risk analysis for an active order."""
    order_id: str
    material_id: str
    material_name: str
    required_quantity: float
    available_quantity: float
    reserved_quantity: float
    incoming_quantity: float
    shortage_quantity: float
    unit: str
    estimated_delay_hours: float
    risk_level: str  # low, medium, high, critical
    explanation: str
    supporting_event_ids: List[str] = Field(default_factory=list)


class QualityRiskAssessment(BaseModel):
    """Quality drift evaluation and roll quarantine assessment."""
    machine_id: str
    process_type: str
    observed_defect_rate_percent: float
    baseline_defect_rate_percent: float
    affected_order_ids: List[str] = Field(default_factory=list)
    suspect_roll_ids: List[str] = Field(default_factory=list)
    quarantine_required: bool = False
    risk_level: str  # low, medium, high, critical
    recommendations: List[str] = Field(default_factory=list)
    supporting_event_ids: List[str] = Field(default_factory=list)


class DeadlineRiskAssessment(BaseModel):
    """Explainable order completion projection and deadline risk."""
    order_id: str
    customer_name: str
    deadline: datetime
    estimated_completion: Optional[datetime] = None
    estimated_lateness_hours: float = 0.0
    risk_category: str  # low, medium, high, critical
    contributing_factors: List[str] = Field(default_factory=list)
    assumptions: List[str] = Field(default_factory=list)
    confidence_level: str = "qualified_estimate"


class RootCauseAnalysis(BaseModel):
    """Structured root cause determination with strict evidence attribution."""
    analysis_id: str
    problem_statement: str
    affected_order_id: Optional[str] = None
    observed_facts: List[str] = Field(default_factory=list)
    inferred_causes: List[Dict[str, Any]] = Field(default_factory=list)
    assumptions: List[str] = Field(default_factory=list)
    missing_information: List[str] = Field(default_factory=list)
    recommended_investigation: str


class RecoveryOption(BaseModel):
    """Discrete recovery alternative generated by the Rescue Engine."""
    option_id: str
    title: str
    description: str
    category: str  # repair, reassign, reschedule, overtime, reallocate, expedite, quarantine_inspect
    action_type: str  # e.g. reassign_machine, execute_repair, reallocate_stock, hold_rolls
    action_parameters: Dict[str, Any] = Field(default_factory=dict)
    feasible: bool = True
    infeasibility_reason: Optional[str] = None
    estimated_delay_reduction_minutes: Optional[float] = None
    estimated_new_completion: Optional[datetime] = None
    estimated_additional_cost: Optional[float] = None
    quality_and_safety_risk: str = "low"  # low, medium, high
    impact_on_other_orders: str = "none"
    assumptions: List[str] = Field(default_factory=list)
    score: float = 0.0
    score_breakdown: Dict[str, float] = Field(default_factory=dict)


class RecoveryPlan(BaseModel):
    """Complete lifecycle recovery recommendation with approval tracking."""
    plan_id: str
    alert_id: str
    problem_statement: str
    status: RecoveryPlanStatus = RecoveryPlanStatus.PROPOSED
    evidence: List[Dict[str, Any]] = Field(default_factory=list)
    options: List[RecoveryOption] = Field(default_factory=list)
    recommended_option_id: Optional[str] = None
    approval_required: bool = True
    approved_by: Optional[str] = None
    approved_at: Optional[datetime] = None
    executed_action: Optional[Dict[str, Any]] = None
    executed_at: Optional[datetime] = None
    idempotency_key: Optional[str] = None
    verification_result: Optional[str] = None  # verified, failed, inconclusive
    verification_details: Optional[str] = None
